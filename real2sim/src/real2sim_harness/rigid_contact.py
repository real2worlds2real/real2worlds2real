"""Validated mesh-contact experiments and measured screw-motion evidence.

No helical constraint or pose trajectory is generated by this module.
"""

from __future__ import annotations

import math

import numpy as np

from .deformable_geometry import surface_mesh


def vector(value, size, name):
    a = np.asarray(value, dtype=float)
    if a.shape != (size,) or not np.isfinite(a).all():
        raise ValueError(f"{name} must contain {size} finite values")
    return a


def validate_request(request):
    c = dict(request)
    c["fps"] = request.get("fps", 24)
    c["frames"] = request.get("frames", 240)
    c["substeps"] = request.get("substeps", 20)
    c["iterations"] = request.get("iterations", 20)
    for key, lo, hi in [
        ("fps", 1, 120),
        ("frames", 2, 1440),
        ("substeps", 1, 128),
        ("iterations", 1, 100),
    ]:
        if type(c[key]) is not int or not lo <= c[key] <= hi:
            raise ValueError(f"{key} must be an integer in [{lo}, {hi}]")
    if not 2 <= len(c.get("bodies", [])) <= 32:
        raise ValueError("Use 2–32 explicit rigid mesh bodies")
    ids = set()
    total_faces = 0
    for body in c["bodies"]:
        if not isinstance(body.get("id"), str) or not body["id"] or body["id"] in ids:
            raise ValueError("Body identifiers must be unique nonempty strings")
        ids.add(body["id"])
        if type(body.get("static", False)) is not bool:
            raise ValueError("static must be boolean")
        v, t, _ = surface_mesh(body["vertices"], body["triangles"], closed=True)
        total_faces += len(t)
        volume = float(
            np.einsum("ij,ij->i", v[t[:, 0]], np.cross(v[t[:, 1]], v[t[:, 2]])).sum() / 6
        )
        if volume <= 1e-15:
            raise ValueError("SDF bodies require outward closed positive-volume meshes")
        q = vector(body.get("pose", [0, 0, 0, 0, 0, 0, 1]), 7, "pose")
        if abs(np.linalg.norm(q[3:]) - 1) > 1e-5:
            raise ValueError("Pose quaternion must be normalized, xyzw")
    if total_faces > 500000:
        raise ValueError("Contact mesh budget exceeded")
    cfg = c.setdefault("contact", {})
    for key, default, lo, hi in [
        ("friction", 0.1, 0, 5),
        ("density_kg_m3", 900.0, 0.01, 1e6),
        ("gap_m", 0.0004, 1e-6, 0.1),
        ("sdf_band_m", 0.001, 1e-6, 0.1),
    ]:
        value = cfg.get(key, default)
        if not isinstance(value, (int, float)) or not math.isfinite(value) or not lo <= value <= hi:
            raise ValueError(f"Invalid contact {key}")
        cfg[key] = value
    cfg.setdefault("sdf_resolution", 256)
    if type(cfg["sdf_resolution"]) is not int or not 32 <= cfg["sdf_resolution"] <= 512:
        raise ValueError("SDF resolution must be 32–512")
    voxel = cfg.get("sdf_voxel_size_m")
    if voxel is not None:
        if (
            not isinstance(voxel, (int, float))
            or not math.isfinite(voxel)
            or not 1e-5 <= voxel <= 0.01
        ):
            raise ValueError("SDF voxel size must be finite and between 1e-5 and .01 metres")
        for body in c["bodies"]:
            if np.ptp(np.asarray(body["vertices"]), axis=0).max() / voxel > 1024:
                raise ValueError("Requested SDF voxel size exceeds the per-body grid budget")
    if cfg["sdf_band_m"] < cfg["gap_m"]:
        raise ValueError("SDF band must cover the contact gap")
    duration = (c["frames"] - 1) / c["fps"]
    dynamic = {b["id"] for b in c["bodies"] if not b.get("static", False)}
    if not dynamic:
        raise ValueError("At least one body must be dynamic")
    if not isinstance(c.get("controls", []), list) or len(c.get("controls", [])) > 128:
        raise ValueError("Use at most 128 control intervals")
    if not isinstance(c.get("thread_checks", []), list) or len(c.get("thread_checks", [])) > 64:
        raise ValueError("Use at most 64 measured thread intervals")
    intervals = {}
    for drive in c.get("controls", []):
        if drive.get("body") not in dynamic:
            raise ValueError("Controls must target a dynamic body")
        start, end = drive.get("start_s", 0), drive.get("end_s", duration)
        if (
            not all(isinstance(x, (int, float)) and math.isfinite(x) for x in [start, end])
            or not 0 <= start < end <= duration + 1e-8
        ):
            raise ValueError("Invalid control interval")
        for a, b in intervals.setdefault(drive["body"], []):
            if max(start, a) < min(end, b):
                raise ValueError("Control intervals on one body must not overlap")
        intervals[drive["body"]].append((start, end))
        for key in [
            "position_target_m",
            "linear_velocity_m_s",
            "force_n",
            "angular_velocity_rad_s",
            "torque_nm",
        ]:
            if key in drive:
                vector(drive[key], 3, key)
        mask = drive.get("position_axes", [False] * 3)
        if len(mask) != 3 or any(type(x) is not bool for x in mask):
            raise ValueError("position_axes must contain three booleans")
        for key in ["position_stiffness", "linear_damping", "angular_gain", "alignment_stiffness"]:
            value = drive.get(key, 0)
            if (
                not isinstance(value, (int, float))
                or not math.isfinite(value)
                or not 0 <= value <= 1e6
            ):
                raise ValueError(f"Invalid {key}")
        for key in ["force_limit_n", "torque_limit_nm"]:
            if (vector(drive.get(key, [0, 0, 0]), 3, key) < 0).any():
                raise ValueError("Wrench limits must be nonnegative")
        stop = drive.get("stop_rotation_after_contact_loss")
        if stop is not None:
            if (
                not isinstance(stop, dict)
                or stop.get("other_body") not in ids
                or stop["other_body"] == drive["body"]
            ):
                raise ValueError("Contact-loss trigger requires a distinct known other_body")
            dwell = stop.get("dwell_seconds", 0.05)
            if (
                not isinstance(dwell, (int, float))
                or not math.isfinite(dwell)
                or not 0 < dwell <= 10
            ):
                raise ValueError("Contact-loss dwell must be positive and at most 10 seconds")
        axis = vector(drive.get("alignment_axis_world", [0, 0, 1]), 3, "alignment axis")
        if abs(np.linalg.norm(axis) - 1) > 1e-5:
            raise ValueError("Alignment axis must be a unit vector")
    vector(c.get("gravity", [0, 0, -9.81]), 3, "gravity")
    for test in c.get("thread_checks", []):
        if (
            test.get("moving_body") not in dynamic
            or test.get("reference_body") not in ids
            or test["moving_body"] == test["reference_body"]
        ):
            raise ValueError("Thread checks require distinct moving and reference bodies")
        axis = vector(test.get("axis_reference", [0, 0, 1]), 3, "thread axis")
        if abs(np.linalg.norm(axis) - 1) > 1e-5:
            raise ValueError("Thread axis must be normalized")
        for key in ["lead_m_per_turn", "tolerance_m"]:
            if (
                not isinstance(test.get(key), (int, float))
                or not math.isfinite(test[key])
                or test[key] == 0
                or (key == "tolerance_m" and test[key] < 0)
            ):
                raise ValueError(f"Invalid thread check {key}")
        minimum = test.get("minimum_turns", 0.25)
        if not isinstance(minimum, (int, float)) or not math.isfinite(minimum) or minimum < 0:
            raise ValueError("Invalid thread minimum_turns")
        a, b = test.get("start_frame", 0), test.get("end_frame", c["frames"] - 1)
        if type(a) is not int or type(b) is not int or not 0 <= a < b < c["frames"]:
            raise ValueError("Invalid thread check frame interval")
    pairs = c.get("separation_checks", [])
    if not isinstance(pairs, list) or len(pairs) > 64:
        raise ValueError("Use at most 64 separation checks")
    for pair in pairs:
        if (
            pair.get("body0") not in ids
            or pair.get("body1") not in ids
            or pair["body0"] == pair["body1"]
        ):
            raise ValueError("Separation checks require two distinct known bodies")
        gap = pair.get("minimum_gap_m")
        if not isinstance(gap, (int, float)) or not math.isfinite(gap) or gap <= 0:
            raise ValueError("Separation gap must be finite and positive")
    return c


def thread_motion(poses, *, lead_m_per_turn, axis=(0, 0, 1), tolerance_m=0.0005, minimum_turns=0.0):
    """Measure poses already expressed relative to a reference body.

    Uses swing/twist decomposition, not Euler yaw, and unwraps continuous turns.
    Rejects the twist singularity and undersampled rotation rather than inventing it.
    """
    if not np.isfinite(minimum_turns) or minimum_turns < 0:
        raise ValueError("Minimum turns must be finite and nonnegative")
    q = np.asarray(poses, dtype=float)
    axis = vector(axis, 3, "thread axis")
    if (
        abs(np.linalg.norm(axis) - 1) > 1e-5
        or q.ndim != 2
        or q.shape[1] != 7
        or len(q) < 2
        or not np.isfinite(q).all()
    ):
        raise ValueError("Use finite relative poses and a normalized thread axis")
    if (
        not np.isfinite(lead_m_per_turn)
        or lead_m_per_turn == 0
        or not np.isfinite(tolerance_m)
        or tolerance_m <= 0
    ):
        raise ValueError("Use a finite nonzero lead and positive tolerance")
    if not np.allclose(np.linalg.norm(q[:, 3:], axis=1), 1, atol=1e-4):
        raise ValueError("Pose quaternion is not normalized")
    # Keep quaternion signs continuous before extracting the twist.
    quat = q[:, 3:].copy()
    for i in range(1, len(quat)):
        if np.dot(quat[i], quat[i - 1]) < 0:
            quat[i] *= -1
    z = quat[:, :3] @ axis
    norm = np.hypot(z, quat[:, 3])
    if (norm < 1e-6).any():
        raise ValueError("Twist is singular near a 180-degree swing")
    raw = 2 * np.arctan2(z / norm, quat[:, 3] / norm)
    angle = np.unwrap(raw)
    if (np.abs(np.diff(angle)) >= np.pi * 0.95).any():
        raise ValueError("Rotation is too coarsely sampled to measure turns")
    turns = (angle - angle[0]) / (2 * np.pi)
    axial = (q[:, :3] - q[0, :3]) @ axis
    residual = axial - lead_m_per_turn * turns
    lateral = q[:, :3] - q[0, :3] - axial[:, None] * axis
    return {
        "ok": bool(np.max(np.abs(residual)) <= tolerance_m and abs(turns[-1]) >= minimum_turns),
        "turns": float(turns[-1]),
        "minimum_turns": minimum_turns,
        "axial_displacement_m": float(axial[-1]),
        "maximum_lead_residual_m": float(np.max(np.abs(residual))),
        "maximum_lateral_drift_m": float(np.linalg.norm(lateral, axis=1).max()),
        "tolerance_m": tolerance_m,
        "scope": "Measured pose/lead consistency only; does not certify thread geometry, contacts or physical calibration.",
    }
